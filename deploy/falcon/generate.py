def render_env(pairs, indent):
    """Render a Kubernetes env list at the indentation the chart expects."""
    pad = " " * indent
    out = []
    for name, value in pairs:
        out.append(f'{pad}- name: {name}')
        out.append(f'{pad}  value: "{value}"')
    return "\n".join(out)


