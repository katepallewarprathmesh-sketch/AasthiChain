def w(path: str, text: str) -> None:
    p = ROOT / path
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(HEADER + text.lstrip("\n"))


def csr_block(indent: str = "") -> str:
    return "\n".join(f"{indent}{k}: {v}" for k, v in CSR.items())


def env_secret(org: str, who: str) -> str:
    return SECRET % f"{org.upper()}_{who.upper()}_SECRET"


def lp_names(org, n):
    return [f"lp{i}-{org}" for i in range(1, n + 1)]


def cp_names(org, n):
    return [f"cp{i}-{org}" for i in range(1, n + 1)]


def vs_names(org, n):
    return [f"vs{i}-{org}" for i in range(1, n + 1)]


