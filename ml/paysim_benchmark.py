"""
External labelled benchmark: PaySim.

PURPOSE. The shipped model is trained on synthetic UPI-shaped data generated by
this repository. The fair objection is that the result might be an artefact of
a generator written to be learnable. This script runs the same model classes
and the same evaluation protocol against an independent, externally published
labelled dataset that this project did not create.

PROVENANCE.
    dataset  https://huggingface.co/datasets/LordNR/AMLGraphX-Paysim
    revision 9dc258656e186b03c4fad26ecb02c3ca9d19c337
    file     paysim.zip -> paysim.csv
    licence  CC BY-SA 4.0 (the HF repo is a redistribution, not the origin)
    origin   PaySim: A financial mobile money simulator for fraud detection
    schema   step,type,amount,nameOrig,oldbalanceOrg,newbalanceOrig,
             nameDest,oldbalanceDest,newbalanceDest,isFraud,isFlaggedFraud
    size     6,362,620 rows | 8,213 frauds | 0.129% | 743 hourly steps (~31 days)

PAYSIM IS ALSO SYNTHETIC. It is a simulator, not production banking data, and
it is mobile money, not UPI. A good score here does not demonstrate real-world
UPI fraud detection. It demonstrates that the modelling approach is not purely
an artefact of our own generator.

DOMAIN MISMATCH, measured rather than assumed. Senders in PaySim are
effectively unique: in a 1.5M-row sample, 99.96% of nameOrig values appear
exactly once and the maximum is 3. There is therefore NO per-sender history in
PaySim, so the velocity and rolling-window half of our feature family cannot be
evaluated here at all. Destinations do repeat (17% appear more than once, max
98), so beneficiary fan-in and novelty are computable. The benchmark therefore
tests a SUBSET of the feature family -- amount, balance, type, counterparty and
temporal -- and says so.

SCOPE. Restricted to TRANSFER and CASH_OUT. Fraud occurs in no other type in
this dataset (PAYMENT, CASH_IN and DEBIT are 0.000%), so including them would
pad the negative class with rows that carry no label signal and flatter every
metric.

SPLIT. Chronological by step: train on the earliest period, then validation,
then test. A random split would let the model see a destination account's
future. The threshold is chosen on validation, never on test.

Usage:  python3 ml/paysim_benchmark.py
The dataset is ~185 MB compressed and is NOT committed; it downloads to /tmp.
"""

import io
import json
import os
import urllib.request
import zipfile

import numpy as np
import pandas as pd
from sklearn.ensemble import GradientBoostingClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (average_precision_score, confusion_matrix,
                             f1_score, precision_recall_curve, precision_score,
                             recall_score, roc_auc_score)
from sklearn.preprocessing import StandardScaler

REVISION = "9dc258656e186b03c4fad26ecb02c3ca9d19c337"
URL = ("https://huggingface.co/datasets/LordNR/AMLGraphX-Paysim/resolve/"
       f"{REVISION}/paysim.zip")
CACHE = "/tmp/paysim/paysim.csv"
SEED = 20260930
MIN_PRECISION = 0.90

# The subset of the UPI feature family that PaySim can actually support.
PAYSIM_FEATURES = [
    "log_amount",
    "balance_ratio",
    "orig_balance_emptied",
    "log_oldbalance_orig",
    "log_oldbalance_dest",
    "payee_fan_in",
    "beneficiary_is_new",
    "is_transfer_type",
    "is_night",
    "is_weekend",
]

# Present in the UPI model, absent or meaningless in PaySim.
NOT_TRANSFERABLE = [
    "txn_count_10m", "txn_count_24h", "log_total_24h", "amount_vs_recent_mean",
    "burstiness", "velocity_x_escalation",      # no per-sender history exists
    "recent_amount_cv", "recent_in_structuring_band",
    "amount_in_structuring_band", "structuring_x_tightness",  # no INR reporting line
    "kyc_unverified", "risky_vpa_fragment",     # no KYC or VPA in PaySim
    "log_account_age_min", "new_account_x_amount",  # no account-opening date
    "distinct_payees_24h",                      # senders do not repeat
]


def fetch():
    if os.path.exists(CACHE):
        return CACHE
    print(f"downloading PaySim at revision {REVISION[:7]} ...")
    raw = urllib.request.urlopen(URL, timeout=1800).read()
    os.makedirs("/tmp/paysim", exist_ok=True)
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        z.extractall("/tmp/paysim")
    return CACHE


def load():
    """Streams the CSV, keeping only TRANSFER/CASH_OUT and compact dtypes.

    nameDest is hashed to uint32 rather than kept as a string: 2.7M distinct
    Python strings exhausts memory here (an earlier attempt was OOM-killed),
    and only equality matters for counting fan-in.
    """
    cols = ["step", "type", "amount", "nameDest", "oldbalanceOrg",
            "newbalanceOrig", "oldbalanceDest", "isFraud"]
    parts = []
    for ch in pd.read_csv(CACHE, usecols=cols, chunksize=1_000_000):
        ch = ch[ch["type"].isin(["TRANSFER", "CASH_OUT"])]
        if ch.empty:
            continue
        parts.append(pd.DataFrame({
            "step": ch["step"].astype("int16"),
            "is_transfer": (ch["type"] == "TRANSFER").astype("int8"),
            "amount": ch["amount"].astype("float32"),
            "dest": pd.util.hash_array(ch["nameDest"].to_numpy()).astype("uint64"),
            "ob_orig": ch["oldbalanceOrg"].astype("float32"),
            "nb_orig": ch["newbalanceOrig"].astype("float32"),
            "ob_dest": ch["oldbalanceDest"].astype("float32"),
            "label": ch["isFraud"].astype("int8"),
        }))
    return pd.concat(parts, ignore_index=True)


def build_features(df):
    df = df.sort_values("step", kind="mergesort").reset_index(drop=True)
    # Prior count of transactions into this destination, strictly before the
    # current row. groupby().cumcount() is exactly "how many came before".
    df["fan_in"] = df.groupby("dest", sort=False).cumcount().astype("int32")

    amount = df["amount"].to_numpy(dtype=np.float64)
    ob_orig = df["ob_orig"].to_numpy(dtype=np.float64)
    nb_orig = df["nb_orig"].to_numpy(dtype=np.float64)
    ob_dest = df["ob_dest"].to_numpy(dtype=np.float64)
    step = df["step"].to_numpy(dtype=np.int64)
    fan_in = df["fan_in"].to_numpy(dtype=np.float64)

    X = np.column_stack([
        np.log1p(np.maximum(amount, 0)),
        amount / (ob_orig + 1.0),
        ((nb_orig == 0) & (ob_orig > 0)).astype(float),
        np.log1p(np.maximum(ob_orig, 0)),
        np.log1p(np.maximum(ob_dest, 0)),
        fan_in,
        (fan_in == 0).astype(float),
        df["is_transfer"].to_numpy(dtype=np.float64),
        ((step % 24) < 5).astype(float),
        (((step // 24) % 7) >= 5).astype(float),
    ])
    return X, df["label"].to_numpy(), step


def pick_threshold(y, p, floor=MIN_PRECISION):
    """Best recall subject to precision >= floor.

    If the floor is unreachable at any threshold, fall back to the best-F1
    point and SAY SO, rather than silently returning 0.5. An earlier version
    returned 0.5 on failure, which on a 0.3% base rate produced a 7% precision
    operating point that looked like a model failure when it was really a
    threshold-selection failure.

    Returns (threshold, recall, floor_met).
    """
    prec, rec, thr = precision_recall_curve(y, p)
    best_t, best_r = None, -1.0
    for pr, rc, t in zip(prec[:-1], rec[:-1], thr):
        if pr >= floor and rc > best_r:
            best_t, best_r = float(t), float(rc)
    if best_t is not None:
        return best_t, best_r, True
    f1s = 2 * prec[:-1] * rec[:-1] / np.clip(prec[:-1] + rec[:-1], 1e-12, None)
    i = int(np.argmax(f1s))
    return float(thr[i]), float(rec[i]), False


def evaluate(name, split, y, p, thr):
    pred = (p >= thr).astype(int)
    tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()
    return {
        "model": name, "split": split, "n": int(len(y)), "positives": int(y.sum()),
        "threshold": round(float(thr), 6),
        "precision": round(float(precision_score(y, pred, zero_division=0)), 4),
        "recall": round(float(recall_score(y, pred, zero_division=0)), 4),
        "f1": round(float(f1_score(y, pred, zero_division=0)), 4),
        "roc_auc": round(float(roc_auc_score(y, p)), 4),
        "pr_auc": round(float(average_precision_score(y, p)), 4),
        "confusion": {"tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp)},
    }


def main():
    fetch()
    df = load()
    X, y, step = build_features(df)
    print(f"\nPaySim (TRANSFER + CASH_OUT only): {len(y):,} rows, "
          f"{int(y.sum()):,} frauds ({y.mean():.3%})")

    c1, c2 = np.quantile(step, 0.60), np.quantile(step, 0.80)
    tr, va, te = step <= c1, (step > c1) & (step <= c2), step > c2
    print(f"chronological split by step -> train {tr.sum():,} (<= {int(c1)}h)  "
          f"val {va.sum():,}  test {te.sum():,}")
    print(f"test fraud rate {y[te].mean():.3%}\n")

    scaler = StandardScaler().fit(X[tr])
    lr = LogisticRegression(max_iter=5000, class_weight="balanced",
                            solver="lbfgs", random_state=SEED)
    lr.fit(scaler.transform(X[tr]), y[tr])
    p_lr_va = lr.predict_proba(scaler.transform(X[va]))[:, 1]
    p_lr_te = lr.predict_proba(scaler.transform(X[te]))[:, 1]
    thr_lr, _, lr_floor_met = pick_threshold(y[va], p_lr_va)

    gb = GradientBoostingClassifier(random_state=SEED, n_estimators=150, max_depth=3)
    gb.fit(X[tr], y[tr])
    p_gb_va = gb.predict_proba(X[va])[:, 1]
    p_gb_te = gb.predict_proba(X[te])[:, 1]
    thr_gb, _, gb_floor_met = pick_threshold(y[va], p_gb_va)

    # Baseline in the spirit of the rules engine: flag large or nocturnal.
    def rules(idx):
        a = np.expm1(X[idx][:, 0])
        return np.clip(np.where(a > 200000, 0.5, 0.0)
                       + X[idx][:, 2] * 0.4 + X[idx][:, 8] * 0.2, 0, 1)
    thr_ru, _, ru_floor_met = pick_threshold(y[va], rules(va))

    results = {
        "validation": [
            evaluate("threshold rules (baseline)", "validation", y[va], rules(va), thr_ru),
            evaluate("logistic-regression", "validation", y[va], p_lr_va, thr_lr),
            evaluate("gradient-boosting", "validation", y[va], p_gb_va, thr_gb),
        ],
        "test": [
            evaluate("threshold rules (baseline)", "test", y[te], rules(te), thr_ru),
            evaluate("logistic-regression", "test", y[te], p_lr_te, thr_lr),
            evaluate("gradient-boosting", "test", y[te], p_gb_te, thr_gb),
        ],
    }
    for split in ("validation", "test"):
        print(f"--- PaySim {split} (threshold chosen on validation) ---")
        print(f"{'model':<30}{'prec':>7}{'rec':>7}{'F1':>7}{'ROC':>8}{'PR-AUC':>9}")
        for r in results[split]:
            print(f"{r['model']:<30}{r['precision']:>7}{r['recall']:>7}"
                  f"{r['f1']:>7}{r['roc_auc']:>8}{r['pr_auc']:>9}")
        print()

    print(f"precision floor {MIN_PRECISION} met? LR={lr_floor_met} GBT={gb_floor_met} rules={ru_floor_met}")
    print("  (where not met, the threshold is the best-F1 point instead)\n")
    print("LR coefficients on PaySim (scaled):")
    for n, c in sorted(zip(PAYSIM_FEATURES, lr.coef_[0]), key=lambda kv: -abs(kv[1])):
        print(f"  {n:<24}{c:+.4f}")

    os.makedirs("model", exist_ok=True)
    with open("model/paysim_benchmark.json", "w") as fh:
        json.dump({
            "dataset": "LordNR/AMLGraphX-Paysim",
            "url": f"https://huggingface.co/datasets/LordNR/AMLGraphX-Paysim/tree/{REVISION}",
            "revision": REVISION,
            "licence": "CC BY-SA 4.0 (redistribution; origin is the PaySim simulator)",
            "is_synthetic": True,
            "is_upi": False,
            "scope": "TRANSFER and CASH_OUT only; fraud rate is 0.000% in all other types",
            "rows_scored": int(len(y)),
            "frauds": int(y.sum()),
            "fraud_rate": round(float(y.mean()), 6),
            "split": "chronological by step, 60/20/20, threshold chosen on validation",
            "features_used": PAYSIM_FEATURES,
            "features_not_transferable": NOT_TRANSFERABLE,
            "domain_mismatch": (
                "PaySim senders are effectively unique (99.96% appear once in a "
                "1.5M-row sample), so no per-sender history exists and the "
                "velocity/rolling-window half of the UPI feature family cannot be "
                "evaluated here. This benchmark tests the amount, balance, type, "
                "counterparty and temporal families only."),
            "caveat": (
                "PaySim is synthetic mobile-money data, not UPI and not production "
                "banking data. These results do not demonstrate real-world UPI "
                "fraud-detection performance. The weights are discarded; this is a "
                "benchmark of the approach, not the shipped model."),
            "coefficients": dict(zip(PAYSIM_FEATURES,
                                     [float(c) for c in lr.coef_[0]])),
            "precision_floor": MIN_PRECISION,
            "precision_floor_met": {"logistic_regression": bool(lr_floor_met),
                                     "gradient_boosting": bool(gb_floor_met),
                                     "rules": bool(ru_floor_met)},
            "results": results,
        }, fh, indent=2)
    print("\nwrote model/paysim_benchmark.json")


if __name__ == "__main__":
    main()
